const STAGE_TOKENS: Record<string, string> = {
  FARROWING: 'FARROWING',
};

function stagesFromWorkbookFilter(filter: string): string[] | null {
  const stages = Object.entries(STAGE_TOKENS)
    .filter(([label]) => new RegExp(`(?:^|/)${label.replace(' ', ' \\s*')}(?:$|/)`, 'i').test(filter))
    .map(([, code]) => code);
  return stages.length ? [...new Set(stages)] : null;
}

