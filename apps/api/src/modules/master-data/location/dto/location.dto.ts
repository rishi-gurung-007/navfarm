// Extends the shared master list contract, which adds sort, dir and
// filter[column] on top of this master's own named filters. The global
// ValidationPipe runs with forbidNonWhitelisted, so a property that is not
// declared is a 400 rather than an ignored parameter.
export class QueryLocationDto extends MasterListQueryDto {
  @ApiProperty({ description: 'Filter by company UUID', required: false })
  @IsOptional()
  @IsUUID()
  companyId?: string;

  @ApiProperty({ description: 'Filter by Nature of Business UUID', required: false })
  @IsOptional()
  @IsString()
  nobId?: string;

  @ApiProperty({ description: 'Filter by Line of Business UUID', required: false })
  @IsOptional()
  @IsString()
  lobId?: string;

  @ApiProperty({ description: 'Filter by parent farm UUID', required: false })
  @IsOptional()
  @IsUUID()
  farmId?: string;

  @ApiProperty({ description: 'Filter by parent shed UUID', required: false })
  @IsOptional()
  @IsUUID()
  shedId?: string;

  @ApiProperty({ description: 'Filter by linked warehouse UUID', required: false })
  @IsOptional()
  @IsUUID()
  warehouseId?: string;

  @ApiProperty({ description: 'Filter by parent location UUID', required: false })
  @IsOptional()
  @IsUUID()
  parentLocationId?: string;

  @ApiProperty({ description: 'Filter by location type', required: false })
  @IsOptional()
  @IsString()
  locationType?: string;

  @ApiProperty({
    description: 'Only locations that may be the parent of a new location of this type — those whose type is in that '
      + "Location Type's allowed_parent_types. A root type (empty list) returns no rows.",
    required: false,
    example: 'SHED',
  })
  @IsOptional()
  @IsString()
  parentForType?: string;

  // The Attached Sheds picker on the Silo form, and the same decision as
  // parentForType above: narrow in SQL, before the page is cut, or the form
  // filters the first 50 rows in the browser and silently offers a subset.
  // A shed already fed by another silo is not on offer at all — that is the
  // "exactly one silo" rule showing up in the picker rather than only in the
  // refusal the save would have produced.
  @ApiProperty({
    description: 'Every active SHED location under this farm — the Attached Sheds picker on the Silo form. A shed may '
      + 'draw from several silos (D7), so nothing here is narrowed by what another silo already feeds.',
    required: false,
  })
  @IsOptional()
  @IsUUID()
  shedsForSilo?: string;

  @ApiProperty({ description: 'Only locations without a parent', required: false })
  @IsOptional()
  @Transform(({ value }) => value === 'true' ? true : value === 'false' ? false : value)
  @IsBoolean()
  rootOnly?: boolean;

  @ApiProperty({ description: 'Filter by active status', required: false })
  @IsOptional()
  @IsBoolean()
  @Type(() => Boolean)
  isActive?: boolean;

  @ApiProperty({ description: 'Search location code or name', required: false })
  @IsOptional()
  @IsString()
  search?: string;

}
